/** «Стаж 3 года», а не «Стаж 3 лет» — заглушки все на «лет», реальные ФИО будут разные. */
export function yearsWord(n: number) {
  const mod100 = n % 100;
  if (mod100 >= 11 && mod100 <= 14) return "лет";
  const mod10 = n % 10;
  if (mod10 === 1) return "год";
  if (mod10 >= 2 && mod10 <= 4) return "года";
  return "лет";
}
